import { isIP } from 'node:net';
import { timingSafeEqual } from 'node:crypto';

export type TrustedGeoCountry = {
  countryCode: string | null;
  source: 'trusted-proxy' | 'authenticated-edge' | 'unknown';
};

export function trustedProxyAddressesFromEnv(value = process.env.TAP_TRUSTED_GEO_PROXY_ADDRESSES): string[] {
  return (value ?? '').split(',').map((item) => item.trim()).filter(Boolean);
}

function normalizedIp(value: string | undefined): string | undefined {
  const candidate = value?.trim().toLowerCase();
  if (!candidate) return undefined;
  if (isIP(candidate) === 4) return candidate;
  if (isIP(candidate) === 6) {
    const mappedV4 = candidate.match(/^::ffff:(\d+\.\d+\.\d+\.\d+)$/)?.[1];
    return mappedV4 && isIP(mappedV4) === 4 ? mappedV4 : candidate;
  }
  return undefined;
}

/**
 * Candidate geolocation boundary. It deliberately returns no client IP and
 * never trusts forwarded headers unless the immediate peer is allowlisted.
 */
export function trustedGeoCountry(input: {
  remoteAddress?: string;
  trustedProxyAddresses?: readonly string[];
  cfConnectingIp?: string;
  cfIpCountry?: string;
}): TrustedGeoCountry {
  const peer = normalizedIp(input.remoteAddress);
  const trustedPeers = new Set((input.trustedProxyAddresses ?? []).map(normalizedIp).filter((ip): ip is string => Boolean(ip)));
  if (!peer || !trustedPeers.has(peer)) return { countryCode: null, source: 'unknown' };

  if (!normalizedIp(input.cfConnectingIp)) return { countryCode: null, source: 'unknown' };
  const country = input.cfIpCountry?.trim().toUpperCase();
  if (!country || !/^[A-Z]{2}$/.test(country) || ['XX', 'ZZ'].includes(country)) {
    return { countryCode: null, source: 'unknown' };
  }
  return { countryCode: country, source: 'trusted-proxy' };
}

export function trustedGeoCountryForRequest(input: {
  remoteAddress?: string;
  headers: Record<string, string | string[] | undefined>;
  trustedProxyAddresses?: readonly string[];
}): TrustedGeoCountry {
  const header = (value: string | string[] | undefined) => Array.isArray(value) ? undefined : value;
  // Explicit peers remain available for isolated comparisons of the old boundary.
  // A runtime loopback allowlist alone must never activate country collection.
  if (!input.trustedProxyAddresses) {
    return authenticatedEdgeGeoCountry({
      mode: process.env.TAP_GEO_MODE,
      environment: process.env.NODE_ENV,
      expectedToken: process.env.TAP_GEO_EDGE_TOKEN,
      providedToken: input.headers['x-tap-geo-auth'],
      country: input.headers['x-tap-geo-country'],
    });
  }
  return trustedGeoCountry({
    remoteAddress: input.remoteAddress,
    trustedProxyAddresses: input.trustedProxyAddresses,
    cfConnectingIp: header(input.headers['cf-connecting-ip']),
    cfIpCountry: header(input.headers['cf-ipcountry']),
  });
}

/** DEV candidate only; the edge must overwrite both custom request headers. */
export function authenticatedEdgeGeoCountry(input: {
  mode?: string;
  environment?: string;
  expectedToken?: string;
  providedToken?: string | string[];
  country?: string | string[];
}): TrustedGeoCountry {
  const unknown = { countryCode: null, source: 'unknown' } as const;
  if (input.mode !== 'authenticated-edge-dev' || input.environment !== 'development') return unknown;
  // A base64url/hex secret with at least 256 bits generated by the operator fits
  // this shape. Length checking alone is not a claim about secret entropy.
  if (!input.expectedToken || !/^[A-Za-z0-9_-]{43,128}$/.test(input.expectedToken)) return unknown;
  if (typeof input.providedToken !== 'string' || !/^[A-Za-z0-9_-]{43,128}$/.test(input.providedToken)) return unknown;
  const expected = Buffer.from(input.expectedToken);
  const provided = Buffer.from(input.providedToken);
  if (expected.length !== provided.length || !timingSafeEqual(expected, provided)) return unknown;
  if (typeof input.country !== 'string') return unknown;
  const country = input.country.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(country) || ['XX', 'ZZ'].includes(country)) return unknown;
  return { countryCode: country, source: 'authenticated-edge' };
}
